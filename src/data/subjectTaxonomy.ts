export function getAllSubjects(): SubjectItem[] {
  return UNIVERSAL_SUBJECTS;
}

export function getSubjectsByFaculty(faculty: AcademicFaculty): SubjectItem[] {
  if (faculty === "all") return UNIVERSAL_SUBJECTS;
  return UNIVERSAL_SUBJECTS.filter((s) => s.faculty === faculty);
}

export function getSubjectById(id: string): SubjectItem | undefined {
  return UNIVERSAL_SUBJECTS.find((s) => s.id === id);
}

export function searchSubjects(query: string, faculty: AcademicFaculty = "all"): SubjectItem[] {
  const clean = query.trim().toLowerCase();
  let list = faculty === "all" ? UNIVERSAL_SUBJECTS : UNIVERSAL_SUBJECTS.filter((s) => s.faculty === faculty);

  if (!clean) return list;

  return list.filter((s) => {
    return (
      s.name.toLowerCase().includes(clean) ||
      s.tagline.toLowerCase().includes(clean) ||
      s.description.toLowerCase().includes(clean) ||
      s.facultyLabel.toLowerCase().includes(clean) ||
      s.commonTopics.some((t) => t.toLowerCase().includes(clean)) ||
      (s.popularCurriculumRef && s.popularCurriculumRef.toLowerCase().includes(clean))
    );
  });
}
